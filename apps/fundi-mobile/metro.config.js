const { getDefaultConfig } = require('expo/metro-config');
const path = require('path');
const projectRoot = __dirname;
const monorepoRoot = path.resolve(projectRoot, '..', '..');
const config = getDefaultConfig(projectRoot);
config.watchFolders = Array.from(new Set([ ...(config.watchFolders || []), path.resolve(projectRoot, 'src'), path.resolve(projectRoot, 'assets'), path.resolve(monorepoRoot, 'packages', 'shared', 'src') ]));
config.resolver.nodeModulesPaths = [ path.resolve(projectRoot, 'node_modules'), path.resolve(monorepoRoot, 'node_modules') ];
config.resolver.disableHierarchicalLookup = false;
config.resolver.extraNodeModules = { 'react-native': path.resolve(projectRoot, 'node_modules', 'react-native'), 'react': path.resolve(projectRoot, 'node_modules', 'react'), 'react-dom': path.resolve(projectRoot, 'node_modules', 'react-dom') };
config.resolver.unstable_enablePackageExports = true;
config.resolver.unstable_enableSymlinks = true;
module.exports = config;
